// 🛑 La firma del APK de release. `keystore.properties` (en `gen/android/`, fuera
// de git) lleva `keyAlias`, `password` (el de la clave y el del almacén) y
// `storeFile`; en la release lo escribe el CI desde los secretos de GitHub
// `ANDROID_KEY_*`, y en el equipo de Pablo, él. Un APK firmado con otra clave
// no se instala encima de otro (Android lo rechaza) y obliga a desinstalar, que
// borra la biblioteca: la clave de verdad no se pierde ni se cambia nunca.
// Sin el fichero el build de release sigue funcionando, pero sale SIN firmar
// (`app-universal-release-unsigned.apk`, que Android no instala).
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}
val firmaDeRelease = keystorePropertiesFile.exists()
if (!firmaDeRelease) {
    logger.warn("WARNING: no hay keystore.properties: el APK de release saldrá SIN FIRMAR.")
}

